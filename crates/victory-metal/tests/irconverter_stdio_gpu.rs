/// Four stages on four concurrent pool workers: one long-lived `--stdio`
/// process each, exactly one job per worker, results matched byte for byte to
/// a serial baseline.
#[test]
fn four_stages_translate_concurrently_without_cross_talk() {
    let _env = EnvGuard::set("VICTORY_METAL_IRCONVERTER", &converter_path());
    let fixtures = fixtures();

    // Serial baseline from a direct daemon.
    let mut baseline_daemon = Daemon::start(&[]);
    let mut expected = Vec::new();
    for (index, (stage, label, dxil)) in fixtures.iter().enumerate() {
        baseline_daemon.send(
            1_000 + index as u64,
            2_000 + index as u64,
            *stage,
            "main",
            dxil,
        );
        let response = baseline_daemon.recv();
        assert_eq!(response.status, 0, "{label}: {:?}", response.payload);
        expected.push(response.payload);
    }
    assert!(baseline_daemon.finish().success());

    let pool = Arc::new(CompilerPool::new(
        PoolConfig {
            workers: 4,
            queue_depth: 8,
            job_timeout: Duration::from_secs(60),
            cache_dir: None,
            converter_version: "victory-metal-test/stdio/1".to_string(),
        },
        Some(worker_path()),
    ));
    assert!(pool_stdio_enabled());
    let barrier = Arc::new(Barrier::new(fixtures.len()));
    let mut handles = Vec::new();
    for (index, (stage, label, dxil)) in fixtures.into_iter().enumerate() {
        let pool = Arc::clone(&pool);
        let barrier = Arc::clone(&barrier);
        handles.push(std::thread::spawn(move || {
            barrier.wait();
            let result = pool.compile(&CompileJob {
                id: 3_000 + index as u64,
                stage,
                entry: "main",
                dxil: &dxil,
            });
            (label, result)
        }));
    }
    for (index, handle) in handles.into_iter().enumerate() {
        let (label, result) = handle.join().expect("caller thread");
        let metallib = result.unwrap_or_else(|err| panic!("{label}: {err}"));
        assert_eq!(
            &metallib, &expected[index],
            "{label}: cross-talk or wrong job"
        );
    }

    let stats = pool.stats();
    assert_eq!(stats.worker_starts, 4, "one persistent worker per slot");
    assert_eq!(stats.worker_jobs, 4);
    assert_eq!(stats.cache_hits, 0);
    assert_eq!(
        stats.cache_misses, 0,
        "a pool built with cache_dir: None does not count misses"
    );
    assert_eq!(
        pool.worker_job_counts(),
        vec![1, 1, 1, 1],
        "each of four concurrent jobs must land on its own worker"
    );
}

/// Cold vs warm throughput on one persistent worker, then a fresh pool over the
/// same warm cache. The first job pays Rosetta/dylib startup; the rest reuse it.
#[test]
fn cold_and_warm_throughput_amortise_rosetta_startup() {
    assert!(pool_stdio_enabled());
    let _env = EnvGuard::set("VICTORY_METAL_IRCONVERTER", &converter_path());
    let dir = TempDir::new("throughput");
    let cache = dir.path().join("cache");
    let base = unhex(CS_DXIL_HEX);
    // 16 content-distinct jobs: trailing bytes after the DXIL container keep the
    // program valid while changing the cache key.
    let jobs: Vec<Vec<u8>> = (0..16u8)
        .map(|extra| {
            let mut dxil = base.clone();
            dxil.extend(std::iter::repeat_n(extra, extra as usize));
            dxil
        })
        .collect();

    let config = PoolConfig {
        workers: 1,
        queue_depth: 32,
        job_timeout: Duration::from_secs(60),
        cache_dir: Some(cache.clone()),
        converter_version: "victory-metal-test/stdio-throughput/1".to_string(),
    };
    let pool = CompilerPool::new(config.clone(), Some(worker_path()));

    let cold = run_jobs(&pool, &jobs);
    let cold_stats = pool.stats();
    assert_eq!(cold_stats.worker_starts, 1, "one worker for all cold jobs");
    assert_eq!(cold_stats.worker_jobs, 16);
    assert_eq!(cold_stats.cache_hits, 0);
    let timings = pool.worker_timings();
    assert_eq!(timings.len(), 1);
    assert_eq!(timings[0].jobs, 16);
    let first = timings[0].first_job_micros;
    let subsequent_avg = timings[0]
        .subsequent_avg_micros()
        .expect("15 subsequent jobs");
    assert!(
        first > subsequent_avg.saturating_mul(2),
        "first job ({first} us) must pay startup and be far slower than the \
         subsequent average ({subsequent_avg} us)"
    );
    let subsequent_max = cold[1..].iter().copied().max().unwrap_or(0);
    assert!(
        first > subsequent_max,
        "job 2..N ({subsequent_max} us max) must all beat job 1 ({first} us)"
    );

    let warm = run_jobs(&pool, &jobs);
    let warm_stats = pool.stats();
    assert_eq!(warm_stats.cache_hits, 16, "second pass must hit the cache");
    assert_eq!(
        warm_stats.worker_jobs, 16,
        "cache hits must not wake a worker"
    );
    assert_eq!(warm_stats.worker_starts, 1);

    // Fresh pool, same warm cache: no worker is ever started.
    let fresh = CompilerPool::new(config, Some(worker_path()));
    let fresh_warm = run_jobs(&fresh, &jobs);
    let fresh_stats = fresh.stats();
    assert_eq!(
        fresh_stats.worker_starts, 0,
        "cache hit must not spawn a worker"
    );
    assert_eq!(fresh_stats.cache_hits, 16);
    assert!(fresh.worker_job_counts().iter().all(|&jobs| jobs == 0));

    report(
        "cold-cache (fresh pool, empty cache)",
        &cold,
        first,
        subsequent_avg,
    );
    report("warm-cache (same pool)", &warm, first, subsequent_avg);
    report("warm-cache (fresh pool)", &fresh_warm, 0, 0);
    println!(
        "cache speedup: {:.1}x (cold {:.3} ms/job vs warm {:.3} ms/job)",
        micros_per_job(&cold) / micros_per_job(&warm),
        micros_per_job(&cold) / 1000.0,
        micros_per_job(&warm) / 1000.0,
    );
    println!(
        "worker job counts: cold {:?}, fresh warm {:?}",
        pool.worker_job_counts(),
        fresh.worker_job_counts()
    );
}

fn run_jobs(pool: &CompilerPool, jobs: &[Vec<u8>]) -> Vec<u64> {
    jobs.iter()
        .enumerate()
        .map(|(index, dxil)| {
            let started = Instant::now();
            let metallib = pool
                .compile(&CompileJob {
                    id: index as u64,
                    stage: CS_STAGE,
                    entry: "main",
                    dxil,
                })
                .unwrap_or_else(|err| panic!("job {index}: {err}"));
            assert_looks_like_metallib(&metallib, &format!("job {index}"));
            u64::try_from(started.elapsed().as_micros()).unwrap_or(u64::MAX)
        })
        .collect()
}

fn micros_per_job(samples: &[u64]) -> f64 {
    samples.iter().sum::<u64>() as f64 / samples.len() as f64
}

fn report(label: &str, samples: &[u64], first: u64, subsequent_avg: u64) {
    let total: u64 = samples.iter().sum();
    println!(
        "throughput[{label}]: {} jobs in {:.3} ms = {:.2} jobs/s, {:.3} ms/job \
         (first {:.3} ms, subsequent avg {:.3} ms)",
        samples.len(),
        total as f64 / 1000.0,
        samples.len() as f64 / (total as f64 / 1e6),
        micros_per_job(samples) / 1000.0,
        first as f64 / 1000.0,
        subsequent_avg as f64 / 1000.0,
    );
}

/// The pool passes `--stdio --converter`, reaps a crashed worker and respawns
/// it for the next job instead of wedging.
#[test]
fn pool_passes_stdio_and_respawns_after_a_crash() {
    let dir = TempDir::new("respawn");
    let _env = EnvGuard::set("VICTORY_METAL_IRCONVERTER", &converter_path());
    let script = dir.path().join("stdio-fixture.sh");
    std::fs::write(
        &script,
        r#"#!/bin/sh
set -u
[ "${1:-}" = "--stdio" ] || exit 21
[ "${2:-}" = "--converter" ] || exit 22
while IFS=' ' read -r magic seq id stage entry_len dxil_len; do
    [ "$magic" = "VMJOB" ] || exit 23
    scratch="${TMPDIR:-/tmp}/victory-stdio-fixture-$$"
    dd bs=1 count="$entry_len" of="$scratch.entry" 2>/dev/null
    dd bs=1 count="$dxil_len" of="$scratch.dxil" 2>/dev/null
    entry=$(cat "$scratch.entry")
    if [ "$entry" = "crash" ]; then
        rm -f "$scratch.entry" "$scratch.dxil"
        exit 9
    fi
    printf 'VMRES %s %s 0 %s\n' "$seq" "$id" "$((entry_len + dxil_len))"
    cat "$scratch.entry"
    cat "$scratch.dxil"
    rm -f "$scratch.entry" "$scratch.dxil"
done
"#,
    )
    .expect("write fixture");
    let mut permissions = std::fs::metadata(&script).expect("stat").permissions();
    permissions.set_mode(0o755);
    std::fs::set_permissions(&script, permissions).expect("chmod");

    let pool = CompilerPool::new(
        PoolConfig {
            workers: 1,
            queue_depth: 4,
            job_timeout: Duration::from_secs(5),
            cache_dir: None,
            converter_version: "victory-metal-test/stdio-fixture/1".to_string(),
        },
        Some(script),
    );
    let first = pool
        .compile(&CompileJob {
            id: 1,
            stage: 8,
            entry: "ok",
            dxil: b"alpha",
        })
        .expect("first job");
    assert_eq!(first, b"okalpha");

    let err = pool
        .compile(&CompileJob {
            id: 2,
            stage: 8,
            entry: "crash",
            dxil: b"beta",
        })
        .expect_err("a dead worker must fail the job");
    assert!(
        matches!(err, PoolError::WorkerExited { job_id: 2 }),
        "unexpected crash error: {err:?}"
    );

    let third = pool
        .compile(&CompileJob {
            id: 3,
            stage: 8,
            entry: "after",
            dxil: b"gamma",
        })
        .expect("pool must respawn the worker");
    assert_eq!(third, b"aftergamma");

    let stats = pool.stats();
    assert!(stats.worker_starts >= 2, "respawn: {stats:?}");
    assert!(stats.worker_restarts >= 1, "crash counted: {stats:?}");
    assert_eq!(
        stats.worker_jobs, 3,
        "three frames reached a worker; the middle one died on it"
    );
}

